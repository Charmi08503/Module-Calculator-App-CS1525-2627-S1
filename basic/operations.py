def add(number_1: float, number_2: float) -> float:
    """Adds two numbers: number_1 and number_2.
    Returns the sum of the two numbers.
    """
    return number_1 + number_2

def subtract(number_1: float, number_2: float) -> float:
    """Subtracts the second number from the first.
    number_1 is the starting number and number_2 is subtracted from it.
    Returns the difference between the numbers.
    """
    return number_1 - number_2

def multiply(number_1: float, number_2: float) -> float:
    """Multiplies two numbers: number_1 and number_2.
    Returns the product of the two numbers.
    """
    return number_1 * number_2

def divide(number_1: float, number_2: float) -> float:
    """Divides the first number by the second.
    number_1 is the number being divided and number_2 is the divisor.
    Returns the quotient of the two numbers.
    """
    return number_1 / number_2